import streamlit as st
import google.generativeai as genai

st.set_page_config(page_title="فاحص قصص الرول بلاي", page_icon="📝")

st.title("📝 نظام فحص قصص الرول بلاي")
st.write("أدخل القصة أدناه للتحقق من الشروط وكشف ما إذا كانت مكتوبة بالذكاء الاصطناعي.")

# إدخال المفتاح في الشريط الجانبي
api_key = st.sidebar.text_input("أدخل مفتاح Gemini API:", type="password")

story = st.text_area("نص القصة:", height=250)

system_prompt = """
أنت مدقق لقصص الرول بلاي ومستكشف للنصوص التوليدية (AI Detector). قم بمراجعة القصة وتوفير التقييم بالتنسيق التالي:

1. **كشف الذكاء الاصطناعي (AI Detection):**
   - قم بتحليل أسلوب الكتابة، المفردات، وتناسق الجمل.
   - حدد نسبة احتمال أن تكون القصة مكتوبة بواسطة الذكاء الاصطناعي (مثل: منخفض جداً، متوسط، عالي جداً) مع ذكر سبب بسيط (مثل: رسمية مفرطة، تكرار أنماط معينة، إلخ).

2. **نتيجة الشروط العامة:**
   - حدد بوضوح هل القصة (مقبولة) أو (غير مقبولة).

3. **تفصيل الشروط:**
   - (حدث محوري/مؤلم في الطفولة): [مستوفى / غير مستوفى]
   - (عدم تحديد المسار مباشرة والاكتفاء بالتلميح): [مستوفى / غير مستوفى]
   - (الواقعية والتسلسل العمري: الاسم، سنة الميلاد، المولد والمنشأ): [مستوفى / غير مستوفى]
   - (الاهتمامات، الطموحات، السلبيات والإيجابيات): [مستوفى / غير مستوفى]
   - (عدم ذكر أحداث داخل السيرفر): [مستوفى / غير مستوفى]

4. **ملاحظات وأسباب الرفض (إن وجدت):**
   - اذكر النقاط المفقودة أو التوجيهات للتعديل بأسلوب مختصر ومباشر.
"""

if st.button("فحص القصة الآن"):
    if not api_key:
        st.error("الرجاء إدخال مفتاح API في الشريط الجانبي أولاً.")
    elif not story:
        st.warning("الرجاء كتابة أو نسخ القصة أولاً.")
    else:
        try:
            genai.configure(api_key=api_key)
            model = genai.GenerativeModel("gemini-1.5-flash")
            response = model.generate_content(f"{system_prompt}\n\nالقصة المراد فحصها:\n{story}")
            
            st.markdown("---")
            st.subheader("نتيجة الفحص:")
            st.write(response.text)
        except Exception as e:
            st.error(f"حدث خطأ: {e}")
